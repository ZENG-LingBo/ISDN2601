// Packs site/dist into one Cloudflare Worker script, site/worker/worker.js, that serves every
// file with the headers from site/_headers (noindex and the rest).
// Run `node site/build.mjs` first, then `node site/worker-build.mjs`.
//
// Why a Worker and not a Pages upload: uploading files to Pages needs a short-lived upload
// token, which the cloud session's network proxy replaces with the saved API token. A Worker
// script uploads in one request with the API token itself.
import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const dist = path.join(here, 'dist');
const outDir = path.join(here, 'worker');

const TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.txt': 'text/plain; charset=utf-8',
};

// Read the headers for "/*" from _headers.
function parseHeaders(text) {
  const headers = {};
  let inAll = false;
  for (const line of text.split('\n')) {
    if (!line.trim() || line.trim().startsWith('#')) continue;
    if (!/^\s/.test(line)) {
      inAll = line.trim() === '/*';
      continue;
    }
    if (inAll) {
      const i = line.indexOf(':');
      headers[line.slice(0, i).trim()] = line.slice(i + 1).trim();
    }
  }
  return headers;
}

async function walk(dir, base = '') {
  const out = [];
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const rel = base + '/' + e.name;
    if (e.isDirectory()) out.push(...(await walk(path.join(dir, e.name), rel)));
    else out.push(rel);
  }
  return out;
}

const headers = parseHeaders(await readFile(path.join(dist, '_headers'), 'utf8'));
const files = {};
for (const rel of await walk(dist)) {
  if (rel === '/_headers') continue;
  const type = TYPES[path.extname(rel)];
  if (!type) throw new Error('No content type for ' + rel);
  files[rel] = { type, body: await readFile(path.join(dist, rel), 'utf8') };
}

const script = `// Generated by site/worker-build.mjs from site/dist. Don't edit by hand.
const HEADERS = ${JSON.stringify(headers, null, 2)};
const FILES = ${JSON.stringify(files)};

export default {
  async fetch(request) {
    const url = new URL(request.url);
    if (request.method !== 'GET' && request.method !== 'HEAD') {
      return new Response('Method not allowed', { status: 405, headers: { ...HEADERS, Allow: 'GET, HEAD' } });
    }
    let p = decodeURIComponent(url.pathname);
    // A folder without its slash: add it, so the page's relative links work.
    if (!p.endsWith('/') && !FILES[p] && FILES[p + '/index.html']) {
      return new Response(null, { status: 301, headers: { ...HEADERS, Location: url.pathname + '/' + url.search } });
    }
    if (p.endsWith('/')) p += 'index.html';
    const f = FILES[p];
    if (!f) {
      return new Response('Page not found', { status: 404, headers: { ...HEADERS, 'Content-Type': 'text/plain; charset=utf-8' } });
    }
    return new Response(request.method === 'HEAD' ? null : f.body, {
      // no-transform: Cloudflare must not change the files, for example by adding its Web Analytics
      // script, which the lbzeng.com zone adds to every page. The site says nothing is sent anywhere.
      headers: { ...HEADERS, 'Content-Type': f.type, 'Cache-Control': 'public, max-age=300, no-transform' },
    });
  },
};
`;

await mkdir(outDir, { recursive: true });
await writeFile(path.join(outDir, 'worker.js'), script);
console.log(`Packed ${Object.keys(files).length} files into site/worker/worker.js (${Math.round(script.length / 1024)} KB)`);
